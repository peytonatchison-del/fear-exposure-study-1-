import { Router } from 'express';
import multer from 'multer';
import fs from 'node:fs';
import path from 'node:path';
import { db } from '../db/index.js';
import { requireResearcher } from '../middleware/auth.js';
import { UPLOADS_DIR } from '../config/paths.js';

const UPLOAD_ROOT = path.join(UPLOADS_DIR, 'stimuli');

const storage = multer.diskStorage({
  destination: (req, file, cb) => {
    const categoryId = (req.body.categoryId || 'uncategorized').replace(/[^a-z0-9_-]/gi, '_');
    const dir = path.join(UPLOAD_ROOT, categoryId);
    fs.mkdirSync(dir, { recursive: true });
    cb(null, dir);
  },
  filename: (req, file, cb) => {
    const ext = path.extname(file.originalname).toLowerCase();
    const level = req.body.level || 'x';
    cb(null, `level${level}-${Date.now()}${ext}`);
  },
});

const ALLOWED_MIME = new Set([
  'image/png',
  'image/jpeg',
  'image/gif',
  'image/webp',
  'video/mp4',
  'video/webm',
  'video/quicktime',
]);

const upload = multer({
  storage,
  limits: { fileSize: 100 * 1024 * 1024 },
  fileFilter: (req, file, cb) => {
    if (!ALLOWED_MIME.has(file.mimetype)) {
      return cb(new Error('Unsupported file type. Allowed: PNG, JPEG, GIF, WEBP, MP4, WEBM, MOV.'));
    }
    cb(null, true);
  },
});

// A separate, more permissive uploader just for audience/crowd backdrop
// videos (Public Speaking Sessions 2-3). Real classroom/YouTube footage
// often isn't MP4/WEBM/MOV specifically (browsers report all sorts of
// video/* mimetypes depending on the source and container), and a multi-
// minute clip can easily be well over the 100MB cap above — both of which
// would previously make an upload silently fail with a confusing "unsupported
// file type" or "file too large" error. This accepts any video/* file up to
// 500MB.
const videoUpload = multer({
  storage,
  limits: { fileSize: 500 * 1024 * 1024 },
  fileFilter: (req, file, cb) => {
    if (!file.mimetype.startsWith('video/')) {
      return cb(new Error('That file doesn’t look like a video. Please choose a video file (mp4, mov, webm, mkv, etc.).'));
    }
    cb(null, true);
  },
});

// A separate uploader just for the College Admissions Session 3 rejection
// letter — an image of the actual letter the researcher wants shown, never
// generated by the app. Images only (a scan or screenshot of the letter),
// up to 20MB.
const letterUpload = multer({
  storage,
  limits: { fileSize: 20 * 1024 * 1024 },
  fileFilter: (req, file, cb) => {
    if (!file.mimetype.startsWith('image/')) {
      return cb(new Error('That file doesn’t look like an image. Please upload an image (a scan, screenshot, or photo of the letter).'));
    }
    cb(null, true);
  },
});

const router = Router();
router.use(requireResearcher);

function serialize(row) {
  return {
    id: row.id,
    categoryId: row.category_id,
    level: row.level,
    contentType: row.content_type,
    content: row.content,
    caption: row.caption,
    durationSeconds: row.duration_seconds,
    audienceVideoUrl: row.audience_video_path || null,
    audienceVideoCredit: row.audience_video_credit || null,
    rejectionLetterUrl: row.rejection_letter_path || null,
    isDemo: !!row.is_demo,
    updatedAt: row.updated_at,
  };
}

router.get('/researcher/stimuli', (req, res) => {
  const rows = db.prepare('SELECT * FROM stimuli ORDER BY category_id, level, is_demo').all();
  res.json(rows.map(serialize));
});

// Set/replace a stimulus with a placeholder string, an external URL, or a
// short text passage — no file upload needed.
router.put('/researcher/stimuli', (req, res) => {
  const { categoryId, level, contentType, content, caption, durationSeconds, isDemo } = req.body || {};
  if (!categoryId || !level || !content || !contentType) {
    return res.status(400).json({ error: 'categoryId, level, contentType, and content are required.' });
  }
  if (!['placeholder', 'url', 'text', 'simulation'].includes(contentType)) {
    return res
      .status(400)
      .json({ error: 'contentType must be placeholder, url, text, or simulation (use file upload for image/video).' });
  }
  upsertStimulus({ categoryId, level, contentType, content, caption, durationSeconds, isDemo });
  res.json({ ok: true });
});

// Upload an approved image/video file for a specific category + level.
router.post('/researcher/stimuli/upload', upload.single('file'), (req, res) => {
  if (!req.file) return res.status(400).json({ error: 'No file uploaded.' });
  const { categoryId, level, caption, durationSeconds, isDemo } = req.body || {};
  if (!categoryId || !level) return res.status(400).json({ error: 'categoryId and level are required.' });

  const relPath = `/uploads/stimuli/${path.basename(path.dirname(req.file.path))}/${req.file.filename}`;
  const contentType = req.file.mimetype.startsWith('video') ? 'video' : 'image';
  upsertStimulus({ categoryId, level, contentType, content: relPath, caption, durationSeconds, isDemo });
  res.json({ ok: true, path: relPath });
});

function upsertStimulus({ categoryId, level, contentType, content, caption, durationSeconds, isDemo }) {
  const demoFlag = isDemo ? 1 : 0;
  db.prepare(
    `INSERT INTO stimuli (category_id, level, content_type, content, caption, duration_seconds, is_demo, updated_at)
     VALUES (@categoryId, @level, @contentType, @content, @caption, @durationSeconds, @isDemo, datetime('now'))
     ON CONFLICT(category_id, level, is_demo) DO UPDATE SET
       content_type = excluded.content_type,
       content = excluded.content,
       caption = excluded.caption,
       duration_seconds = excluded.duration_seconds,
       updated_at = datetime('now')`
  ).run({
    categoryId,
    level: Number(level),
    contentType,
    content,
    caption: caption || null,
    durationSeconds: durationSeconds ? Number(durationSeconds) : null,
    isDemo: demoFlag,
  });
}

// Upload/replace the researcher's own classroom/audience video, used as the
// visual backdrop for a 'simulation' stimulus (Public Speaking Sessions 2-3)
// instead of the default illustrated audience. Stored in a separate column
// from content/content_type, so it never interferes with the simulation
// lookup key those columns hold. Uses the permissive videoUpload instance
// above (any video/* mimetype, up to 500MB) since real source footage rarely
// matches the stricter image+video allowlist used for exposure stimuli.
router.post('/researcher/stimuli/:id/audience-video', videoUpload.single('file'), (req, res) => {
  if (!req.file) return res.status(400).json({ error: 'No file uploaded.' });
  const row = db.prepare('SELECT * FROM stimuli WHERE id = ?').get(req.params.id);
  if (!row) return res.status(404).json({ error: 'Stimulus not found.' });
  // Remove any previous audience video for this stimulus before saving the new path.
  if (row.audience_video_path && row.audience_video_path.startsWith('/uploads/')) {
    fs.rm(path.join(UPLOADS_DIR, row.audience_video_path.replace(/^\/uploads\//, '')), { force: true }, () => {});
  }
  const relPath = `/uploads/stimuli/${path.basename(path.dirname(req.file.path))}/${req.file.filename}`;
  // An optional credit/subtext line can be sent alongside the file in the
  // same form submission; if omitted, whatever credit was already saved
  // (if any) is left untouched.
  const credit = typeof req.body.credit === 'string' ? req.body.credit.trim() : undefined;
  if (credit === undefined) {
    db.prepare(`UPDATE stimuli SET audience_video_path = ?, updated_at = datetime('now') WHERE id = ?`).run(
      relPath,
      req.params.id
    );
  } else {
    db.prepare(
      `UPDATE stimuli SET audience_video_path = ?, audience_video_credit = ?, updated_at = datetime('now') WHERE id = ?`
    ).run(relPath, credit || null, req.params.id);
  }
  res.json({ ok: true, path: relPath });
});

