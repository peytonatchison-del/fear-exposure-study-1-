router.delete('/researcher/stimuli/:id', (req, res) => {
  const row = db.prepare('SELECT * FROM stimuli WHERE id = ?').get(req.params.id);
  if (!row) return res.status(404).json({ error: 'Stimulus not found.' });
  try {
    db.prepare('DELETE FROM stimuli WHERE id = ?').run(req.params.id);
  } catch (err) {
    if (err.code === 'SQLITE_CONSTRAINT_FOREIGNKEY') {
      return res.status(409).json({
        error:
          'This stimulus can’t be reset because one or more participant responses already reference it. ' +
          'Use the Edit button to change its content instead, or clear the relevant demo/participant data first.',
      });
    }
    throw err;
  }
  if (row.content_type !== 'placeholder' && row.content?.startsWith('/uploads/')) {
    // row.content is a URL path like /uploads/stimuli/<category>/<file> —
    // resolve it against the actual configured UPLOADS_DIR (which may be a
    // mounted persistent volume in production), not a fixed relative path.
    fs.rm(path.join(UPLOADS_DIR, row.content.replace(/^\/uploads\//, '')), { force: true }, () => {});
  }
  if (row.audience_video_path && row.audience_video_path.startsWith('/uploads/')) {
    fs.rm(path.join(UPLOADS_DIR, row.audience_video_path.replace(/^\/uploads\//, '')), { force: true }, () => {});
  }
  if (row.rejection_letter_path && row.rejection_letter_path.startsWith('/uploads/')) {
    fs.rm(path.join(UPLOADS_DIR, row.rejection_letter_path.replace(/^\/uploads\//, '')), { force: true }, () => {});
  }
  res.json({ ok: true });
});

