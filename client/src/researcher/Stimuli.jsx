import React, { useEffect, useState } from 'react';
import { api } from '../api.js';

const LEVELS = [1, 2, 3, 4, 5];

// Interactive simulations available for the "Interactive Simulation" mode.
// The value is what's stored in stimuli.content and matched by the
// participant-facing SIMULATIONS map in ExposureSession.jsx.
const SIMULATIONS = [
  {
    value: 'job_application_narrative_intro',
    label: 'Applying for a Job — Narrative Intro (5-slide story building up to a job application, 10s wait per slide)',
  },
  {
    value: 'job_application_resume_form',
    label:
      'Applying for a Job — Résumé Form (5 open-ended questions: objective, education, skills, experience, achievements; 2:30 countdown, must answer all to continue)',
  },
  {
    value: 'job_application_offer_negotiation',
    label:
      'Applying for a Job — Offer & Negotiation (fake interview-offer email → draft a counter-offer email asking for $90,000 → employer meets in the middle at $85,000)',
  },
  {
    value: 'job_application_live_interview',
    label:
      'Applying for a Job — Live Interview (researcher-uploaded interviewer video + participant camera picture-in-picture, 3 questions at 30s each)',
  },
  {
    value: 'college_admissions_narrative_intro',
    label:
      'College Admissions — Narrative Intro (5-slide story building up to checking a decision, 10s wait per slide) — legacy, replaced by the Applying for a Job simulations above',
  },
  {
    value: 'college_friend_group_chat',
    label:
      'Friend Group Text Thread — Community College Announcement (animated group chat — a friend announces he\'s going to community college instead of UF) — legacy, not used by the default schedule',
  },
  {
    value: 'college_admissions_rejection_email',
    label:
      'Admissions Email + Rejection Letter (fake email opens into an envelope, revealing a rejection letter you upload yourself below) — legacy, replaced by the Applying for a Job simulations above',
  },
  {
    value: 'college_friend_group_chat_rejection',
    label:
      'Friend Group Text Thread — Rejection Reaction (animated group chat — you tell your friends you didn\'t get in, and talk through your backup plan) — legacy, not used by the default schedule',
  },
  {
    value: 'financial_aid_status_uf',
    label:
      'Financial Aid Email + Balance Page (fictional tuition/financial-aid email and account summary, 15-second minimum view) — legacy, not used by the default schedule',
  },
  {
    value: 'admissions_portal_uf',
    label:
      'College Admissions Portal (fictional "University of Florida" applicant portal — new-message notification → decision email → stops before revealing any decision) — legacy, not used by the default schedule',
  },
  {
    value: 'public_speaking_narrative_intro',
    label: 'Public Speaking — Narrative Intro (5-slide story building up to a presentation, 10s wait per slide)',
  },
  {
    value: 'public_speaking_audience_readaloud',
    label: 'Public Speaking — Small Audience Read-Aloud (preset passage overlaid on your own class video, gated countdown timer)',
  },
  {
    value: 'public_speaking_teleprompter',
    label: 'Public Speaking — Large Audience Teleprompter (longer script overlaid on your own class video, paced by spacebar, tap, or click, 1:25 timer with a +10s button)',
  },
  {
    value: 'public_speaking_own_response',
    label: 'Public Speaking — Own Response on Camera (live news-interview framing, 30s prep, 35s "on air")',
  },
  {
    value: 'test_anxiety_narrative_intro',
    label: 'Test-Taking — Narrative Intro (5-slide story building up to a test, 10s wait per slide)',
  },
  {
    value: 'test_anxiety_easy_test',
    label: 'Test-Taking — Easy Quiz (5 very easy multiple-choice questions, no timer)',
  },
  {
    value: 'test_anxiety_moderate_test',
    label:
      'Test-Taking — Moderate Test (10 multiple-choice questions, 1-min countdown with a +10s button, must answer all to submit unless time runs out first)',
  },
  {
    value: 'test_anxiety_difficult_test',
    label:
      'Test-Taking — Difficult Test (1-min reading passage that auto-advances, then 8 multiple-choice + 2 written-response questions under a 1-min countdown, ends on a fake 60% results screen with a 10s wait)',
  },
];
const SIMULATION_LABELS = Object.fromEntries(SIMULATIONS.map((s) => [s.value, s.label.split(' (')[0]]));

// These two simulations show a real audience via video (overlaid with the
// passage/script text) instead of the default illustrated crowd, so both
// get the video-upload + credit controls in the editor below.
const AUDIENCE_VIDEO_SIMULATIONS = ['public_speaking_audience_readaloud', 'public_speaking_teleprompter'];

// This simulation reveals a rejection letter that's never generated by the
// app — the researcher uploads their own image of it here, same idea as the
// audience-video upload above.
const REJECTION_LETTER_SIMULATIONS = ['college_admissions_rejection_email'];

// Applying for a Job Session 4's live-interview simulation shows a
// researcher-uploaded "interviewer" video (with the participant's own camera
// as a picture-in-picture overlay) instead of anything the app generates —
// same upload-your-own-media idea as the two lists above.
const INTERVIEW_VIDEO_SIMULATIONS = ['job_application_live_interview'];

export default function Stimuli() {
  const [categories, setCategories] = useState([]);
  const [stimuli, setStimuli] = useState([]);
  const [editing, setEditing] = useState(null); // { categoryId, level }
  const [form, setForm] = useState({ mode: 'placeholder', content: '', caption: '', durationSeconds: '' });
  const [file, setFile] = useState(null);
  const [status, setStatus] = useState('');
  const [error, setError] = useState('');
  const [audienceVideoFile, setAudienceVideoFile] = useState(null);
  const [audienceVideoCredit, setAudienceVideoCredit] = useState('');
  const [audienceVideoStatus, setAudienceVideoStatus] = useState('');
  const [uploadingVideo, setUploadingVideo] = useState(false);
  const [uploadProgress, setUploadProgress] = useState(0);
  const [rejectionLetterFile, setRejectionLetterFile] = useState(null);
  const [rejectionLetterStatus, setRejectionLetterStatus] = useState('');
  const [uploadingLetter, setUploadingLetter] = useState(false);
  const [interviewVideoFile, setInterviewVideoFile] = useState(null);
  const [interviewVideoStatus, setInterviewVideoStatus] = useState('');
  const [uploadingInterviewVideo, setUploadingInterviewVideo] = useState(false);
  const [interviewVideoProgress, setInterviewVideoProgress] = useState(0);

  async function load() {
    const [protocol, stimuliList] = await Promise.all([api.getFullProtocol(), api.getStimuli()]);
    setCategories(protocol.fearCategories);
    setStimuli(stimuliList);
  }

  useEffect(() => {
    load();
  }, []);

  function findStimulus(categoryId, level) {
    return stimuli.find((s) => s.categoryId === categoryId && s.level === level && !s.isDemo);
  }

  function openEditor(categoryId, level) {
    const existing = findStimulus(categoryId, level);
    setEditing({ categoryId, level });
    const textLikeTypes = ['placeholder', 'text', 'url', 'simulation'];
    setForm({
      mode: existing && (existing.contentType === 'image' || existing.contentType === 'video') ? 'upload' : (existing?.contentType || 'placeholder'),
      content: existing && textLikeTypes.includes(existing.contentType) ? existing.content : '',
      caption: existing?.caption || '',
      durationSeconds: existing?.durationSeconds || '',
    });
    setFile(null);
    setStatus('');
    setError('');
    setAudienceVideoFile(null);
    setAudienceVideoCredit(existing?.audienceVideoCredit || '');
    setAudienceVideoStatus('');
    setUploadingVideo(false);
    setUploadProgress(0);
    setRejectionLetterFile(null);
    setRejectionLetterStatus('');
    setUploadingLetter(false);
    setInterviewVideoFile(null);
    setInterviewVideoStatus('');
    setUploadingInterviewVideo(false);
    setInterviewVideoProgress(0);
  }

  async function handleSave() {
    setError('');
    try {
      if (form.mode === 'upload') {
        if (!file) throw new Error('Choose a file to upload.');
        const fd = new FormData();
        fd.append('file', file);
        fd.append('categoryId', editing.categoryId);
        fd.append('level', editing.level);
        fd.append('caption', form.caption);
        if (form.durationSeconds) fd.append('durationSeconds', form.durationSeconds);
        await api.uploadStimulus(fd);
      } else {
        if (!form.content.trim()) throw new Error('Content is required.');
        await api.putStimulus({
          categoryId: editing.categoryId,
          level: editing.level,
          contentType: form.mode,
          content: form.content,
          caption: form.caption,
          durationSeconds: form.durationSeconds ? Number(form.durationSeconds) : undefined,
        });
      }
      setStatus('Saved.');
      setEditing(null);
      await load();
    } catch (err) {
      setError(err.message);
    }
  }

  async function handleDelete(id) {
    await api.deleteStimulus(id);
    await load();
  }

  async function handleUploadAudienceVideo(stimulusId) {
    setError('');
    setAudienceVideoStatus('');
    if (!audienceVideoFile) {
      setError('Choose a video file first.');
      return;
    }
    if (!stimulusId) {
      setError('Could not find this stimulus to attach the video to — try closing and reopening the editor.');
      return;
    }
    setUploadingVideo(true);
    setUploadProgress(0);
    try {
      const fd = new FormData();
      fd.append('file', audienceVideoFile);
      fd.append('credit', audienceVideoCredit || '');
      await api.uploadAudienceVideoWithProgress(stimulusId, fd, setUploadProgress);
      setAudienceVideoFile(null);
      setAudienceVideoStatus('Class video uploaded.');
      await load();
    } catch (err) {
      setError(err.message);
    } finally {
      setUploadingVideo(false);
    }
  }

  async function handleSaveAudienceVideoCredit(stimulusId) {
    setError('');
    setAudienceVideoStatus('');
    try {
      await api.updateAudienceVideoCredit(stimulusId, audienceVideoCredit || '');
      setAudienceVideoStatus('Credit saved.');
      await load();
    } catch (err) {
      setError(err.message);
    }
  }

  async function handleClearAudienceVideo(stimulusId) {
    setError('');
    setAudienceVideoStatus('');
    try {
      await api.clearAudienceVideo(stimulusId);
      setAudienceVideoCredit('');
      setAudienceVideoStatus('Class video removed — back to the default illustrated audience.');
      await load();
    } catch (err) {
      setError(err.message);
    }
  }

  async function handleUploadRejectionLetter(stimulusId) {
    setError('');
    setRejectionLetterStatus('');
    if (!rejectionLetterFile) {
      setError('Choose an image file first.');
      return;
    }
    if (!stimulusId) {
      setError('Could not find this stimulus to attach the letter to — try closing and reopening the editor.');
      return;
    }
    setUploadingLetter(true);
    try {
      const fd = new FormData();
      fd.append('file', rejectionLetterFile);
      await api.uploadRejectionLetter(stimulusId, fd);
      setRejectionLetterFile(null);
      setRejectionLetterStatus('Rejection letter uploaded.');
      await load();
    } catch (err) {
      setError(err.message);
    } finally {
      setUploadingLetter(false);
    }
  }

  async function handleClearRejectionLetter(stimulusId) {
    setError('');
    setRejectionLetterStatus('');
    try {
      await api.clearRejectionLetter(stimulusId);
      setRejectionLetterStatus('Rejection letter removed.');
      await load();
    } catch (err) {
      setError(err.message);
    }
  }

  async function handleUploadInterviewVideo(stimulusId) {
    setError('');
    setInterviewVideoStatus('');
    if (!interviewVideoFile) {
      setError('Choose a video file first.');
      return;
    }
    if (!stimulusId) {
      setError('Could not find this stimulus to attach the video to — try closing and reopening the editor.');
      return;
    }
    setUploadingInterviewVideo(true);
    setInterviewVideoProgress(0);
    try {
      const fd = new FormData();
      fd.append('file', interviewVideoFile);
      await api.uploadInterviewVideoWithProgress(stimulusId, fd, setInterviewVideoProgress);
      setInterviewVideoFile(null);
      setInterviewVideoStatus('Interview video uploaded.');
      await load();
    } catch (err) {
      setError(err.message);
    } finally {
      setUploadingInterviewVideo(false);
    }
  }

  async function handleClearInterviewVideo(stimulusId) {
    setError('');
    setInterviewVideoStatus('');
    try {
      await api.clearInterviewVideo(stimulusId);
      setInterviewVideoStatus('Interview video removed.');
      await load();
    } catch (err) {
      setError(err.message);
    }
  }

  return (
    <div>
      <h1 className="screen-title">Exposure Stimuli</h1>
      <p className="lead">
        Every cell below must contain the exact IRB-approved material before real data collection begins. Nothing
        here is generated automatically — you upload or specify each item.
      </p>
      {status && <p style={{ color: 'var(--calm-teal)' }}>{status}</p>}

      <div className="rd-card" style={{ overflowX: 'auto' }}>
        <table className="rd-table">
          <thead>
            <tr>
              <th>Category</th>
              {LEVELS.map((lvl) => (
                <th key={lvl}>Level {lvl}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {categories.map((cat) => (
              <tr key={cat.id}>
                <td style={{ fontWeight: 600 }}>{cat.name}</td>
                {LEVELS.map((lvl) => {
                  const s = findStimulus(cat.id, lvl);
                  return (
                    <td key={lvl}>
                      <div className="rd-stimulus-cell">
                        <span className={`badge ${s && s.contentType !== 'placeholder' ? 'badge-active' : 'badge-blocked'}`}>
                          {s ? s.contentType : 'missing'}
                        </span>
                        <p className="rd-stimulus-preview">
                          {s?.contentType === 'simulation'
                            ? SIMULATION_LABELS[s.content] || s.content
                            : s?.content?.slice(0, 60) || '—'}
                        </p>
                        <button className="btn btn-secondary" style={{ width: 'auto' }} onClick={() => openEditor(cat.id, lvl)}>
                          Edit
                        </button>
                        {s && s.contentType !== 'placeholder' && (
                          <button className="btn btn-danger" style={{ width: 'auto', marginTop: 6 }} onClick={() => handleDelete(s.id)}>
                            Reset
                          </button>
                        )}
                      </div>
                    </td>
                  );
                })}
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {editing && (
        <div className="rd-card">
          <h2 className="section-title" style={{ marginTop: 0 }}>
            Edit Stimulus — {categories.find((c) => c.id === editing.categoryId)?.name}, Level {editing.level}
          </h2>

          <div className="mode-toggle" style={{ maxWidth: 600, flexWrap: 'wrap' }}>
            {['placeholder', 'text', 'url', 'simulation', 'upload'].map((m) => (
              <button key={m} className={form.mode === m ? 'active' : ''} onClick={() => setForm((f) => ({ ...f, mode: m }))}>
                {m === 'upload' ? 'Image/Video' : m === 'simulation' ? 'Interactive Simulation' : m}
              </button>
            ))}
          </div>

          {form.mode === 'simulation' ? (
            <div className="field-block">
              <label className="field-label">Interactive simulation</label>
              <select value={form.content} onChange={(e) => setForm((f) => ({ ...f, content: e.target.value }))}>
                <option value="">Choose a simulation…</option>
                {SIMULATIONS.map((sim) => (
                  <option key={sim.value} value={sim.value}>
                    {sim.label}
                  </option>
                ))}
              </select>
              <p style={{ fontSize: '0.85rem', color: 'var(--text-secondary)', marginTop: 8 }}>
                Interactive simulations are self-paced (the participant clicks through them) — there's no fixed
                viewing timer for this stimulus type, and this scenario intentionally stops before showing any
                outcome.
              </p>

              {AUDIENCE_VIDEO_SIMULATIONS.includes(form.content) && (
                <div className="field-block" style={{ marginTop: 16 }}>
                  <label className="field-label">Class audience video (optional)</label>
                  <p style={{ fontSize: '0.85rem', color: 'var(--text-secondary)', marginBottom: 8 }}>
                    Upload a video of a real or simulated classroom to use as the audience for this session — the
                    {form.content === 'public_speaking_teleprompter' ? ' script' : ' passage'} is overlaid directly on
                    top of it so participants see both at once, in place of the default illustrated audience. Any
                    video format is accepted, up to 500MB.{' '}
                    {findStimulus(editing.categoryId, editing.level)?.audienceVideoUrl
                      ? 'A video is currently set for this session.'
                      : 'No video set yet — participants currently see the default illustrated audience.'}
                  </p>
                  <input
                    type="file"
                    accept="video/*"
                    disabled={uploadingVideo}
                    onChange={(e) => setAudienceVideoFile(e.target.files[0])}
                  />
                  <div className="rd-row" style={{ marginTop: 8 }}>
                    <button
                      className="btn btn-secondary"
                      style={{ width: 'auto' }}
                      disabled={uploadingVideo}
                      onClick={() => handleUploadAudienceVideo(findStimulus(editing.categoryId, editing.level)?.id)}
                    >
                      {uploadingVideo ? `Uploading… ${uploadProgress}%` : 'Upload Video'}
                    </button>
                    {findStimulus(editing.categoryId, editing.level)?.audienceVideoUrl && (
                      <button
                        className="btn btn-danger"
                        style={{ width: 'auto' }}
                        disabled={uploadingVideo}
                        onClick={() => handleClearAudienceVideo(findStimulus(editing.categoryId, editing.level)?.id)}
                      >
                        Remove Video
                      </button>
                    )}
                  </div>
                  {uploadingVideo && (
                    <p style={{ fontSize: '0.82rem', color: 'var(--text-secondary)', marginTop: 6 }}>
                      Large videos can take a while, especially on a slower connection — keep this tab open until it
                      reaches 100%.
                    </p>
                  )}

                  <label className="field-label" style={{ marginTop: 14 }}>
                    Video credit (optional — shown as small subtext under the video)
                  </label>
                  <input
                    type="text"
                    value={audienceVideoCredit}
                    placeholder="e.g. Video courtesy of Virtual Reality Public Speaking (YouTube)"
                    onChange={(e) => setAudienceVideoCredit(e.target.value)}
                  />
                  <div className="rd-row" style={{ marginTop: 8 }}>
                    <button
                      className="btn btn-secondary"
                      style={{ width: 'auto' }}
                      onClick={() => handleSaveAudienceVideoCredit(findStimulus(editing.categoryId, editing.level)?.id)}
                    >
                      Save Credit
                    </button>
                  </div>

                  {audienceVideoStatus && <p style={{ color: 'var(--calm-teal)', marginTop: 8 }}>{audienceVideoStatus}</p>}
                </div>
              )}

              {REJECTION_LETTER_SIMULATIONS.includes(form.content) && (
                <div className="field-block" style={{ marginTop: 16 }}>
                  <label className="field-label">Rejection letter (upload required for this stimulus)</label>
                  <p style={{ fontSize: '0.85rem', color: 'var(--text-secondary)', marginBottom: 8 }}>
                    This scenario never generates a letter on its own — upload an image (a scan, screenshot, or
                    photo) of the exact rejection letter you want revealed once the participant opens the envelope.
                    PNG, JPEG, GIF, or WEBP, up to 20MB.{' '}
                    {findStimulus(editing.categoryId, editing.level)?.rejectionLetterUrl
                      ? 'A letter is currently set for this session.'
                      : 'No letter uploaded yet — participants will currently see a placeholder note instead.'}
                  </p>
                  <input
                    type="file"
                    accept="image/*"
                    disabled={uploadingLetter}
                    onChange={(e) => setRejectionLetterFile(e.target.files[0])}
                  />
                  <div className="rd-row" style={{ marginTop: 8 }}>
                    <button
                      className="btn btn-secondary"
                      style={{ width: 'auto' }}
                      disabled={uploadingLetter}
                      onClick={() => handleUploadRejectionLetter(findStimulus(editing.categoryId, editing.level)?.id)}
                    >
                      {uploadingLetter ? 'Uploading…' : 'Upload Letter'}
                    </button>
                    {findStimulus(editing.categoryId, editing.level)?.rejectionLetterUrl && (
                      <button
                        className="btn btn-danger"
                        style={{ width: 'auto' }}
                        disabled={uploadingLetter}
                        onClick={() => handleClearRejectionLetter(findStimulus(editing.categoryId, editing.level)?.id)}
                      >
                        Remove Letter
                      </button>
                    )}
                  </div>
                  {rejectionLetterStatus && <p style={{ color: 'var(--calm-teal)', marginTop: 8 }}>{rejectionLetterStatus}</p>}
                </div>
              )}

              {INTERVIEW_VIDEO_SIMULATIONS.includes(form.content) && (
                <div className="field-block" style={{ marginTop: 16 }}>
                  <label className="field-label">Interviewer video (upload required for this stimulus)</label>
                  <p style={{ fontSize: '0.85rem', color: 'var(--text-secondary)', marginBottom: 8 }}>
                    This scenario never generates an interviewer on its own — upload a video of someone asking
                    interview questions (a real recording, or even a webcam clip of a researcher reading them) for
                    the participant to respond to. The participant's own camera appears in a small picture-in-picture
                    box over the top-right corner while they answer. Any video format is accepted, up to 500MB.{' '}
                    {findStimulus(editing.categoryId, editing.level)?.interviewVideoUrl
                      ? 'A video is currently set for this session.'
                      : 'No video uploaded yet — participants will currently see a placeholder note instead of an interviewer.'}
                  </p>
                  <input
                    type="file"
                    accept="video/*"
                    disabled={uploadingInterviewVideo}
                    onChange={(e) => setInterviewVideoFile(e.target.files[0])}
                  />
                  <div className="rd-row" style={{ marginTop: 8 }}>
                    <button
                      className="btn btn-secondary"
                      style={{ width: 'auto' }}
                      disabled={uploadingInterviewVideo}
                      onClick={() => handleUploadInterviewVideo(findStimulus(editing.categoryId, editing.level)?.id)}
                    >
                      {uploadingInterviewVideo ? `Uploading… ${interviewVideoProgress}%` : 'Upload Video'}
                    </button>
                    {findStimulus(editing.categoryId, editing.level)?.interviewVideoUrl && (
                      <button
                        className="btn btn-danger"
                        style={{ width: 'auto' }}
                        disabled={uploadingInterviewVideo}
                        onClick={() => handleClearInterviewVideo(findStimulus(editing.categoryId, editing.level)?.id)}
                      >
                        Remove Video
                      </button>
                    )}
                  </div>
                  {uploadingInterviewVideo && (
                    <p style={{ fontSize: '0.82rem', color: 'var(--text-secondary)', marginTop: 6 }}>
                      Large videos can take a while, especially on a slower connection — keep this tab open until it
                      reaches 100%.
                    </p>
                  )}
                  {interviewVideoStatus && <p style={{ color: 'var(--calm-teal)', marginTop: 8 }}>{interviewVideoStatus}</p>}
                </div>
              )}
            </div>
          ) : form.mode !== 'upload' ? (
            <div className="field-block">
              <label className="field-label">
                {form.mode === 'url' ? 'External URL' : form.mode === 'text' ? 'Text passage to display' : 'Placeholder text'}
              </label>
              <textarea value={form.content} onChange={(e) => setForm((f) => ({ ...f, content: e.target.value }))} />
            </div>
          ) : (
            <div className="field-block">
              <label className="field-label">Upload approved image or video</label>
              <input type="file" accept="image/*,video/*" onChange={(e) => setFile(e.target.files[0])} />
            </div>
          )}

          <div className="rd-grid-2">
            <div className="field-block">
              <label className="field-label">Caption (optional)</label>
              <input type="text" value={form.caption} onChange={(e) => setForm((f) => ({ ...f, caption: e.target.value }))} />
            </div>
            <div className="field-block">
              <label className="field-label">Duration override, seconds (optional)</label>
              <input type="text" value={form.durationSeconds} onChange={(e) => setForm((f) => ({ ...f, durationSeconds: e.target.value }))} />
            </div>
          </div>

          {error && <p className="error-text">{error}</p>}

          <div className="rd-row">
            <button className="btn btn-primary" style={{ width: 'auto' }} onClick={handleSave}>
              Save Stimulus
            </button>
            <button className="btn btn-secondary" style={{ width: 'auto' }} onClick={() => setEditing(null)}>
              Cancel
            </button>
          </div>
        </div>
      )}
    </div>
  );
}
